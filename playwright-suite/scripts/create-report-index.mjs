async function workbookSummary(filePath, name) {
  const workbook = new ExcelJS.Workbook();
  await workbook.xlsx.readFile(filePath);
  const summarySheet = workbook.getWorksheet('Summary');
  const summary = {};
  summarySheet?.eachRow((row) => {
    const key = String(row.getCell(1).text || '').trim();
    if (key) summary[key] = row.getCell(2).text;
  });
  return {
    name,
    filePath,
    suite: summary['Suite'] || name.replace(/-latest\.xlsx$/, ''),
    passed: summary.Passed || '0',
    failed: summary.Failed || '0',
    skipped: summary.Skipped || '0',
    executionRows: summary['Execution rows'] || '0',
    screenshots: summary['Screenshots captured'] || '0',
  };
}

function workbookTable(rows) {
  if (rows.length === 0) return '<p class="missing">No environment-scoped Excel reports were found.</p>';
  return `<table><thead><tr><th>Suite</th><th>Executed</th><th>Pass</th><th>Fail</th><th>Skipped</th><th>Screenshots</th><th>Workbook</th></tr></thead><tbody>${rows.map((row) => `<tr><td>${escapeHtml(row.suite)}</td><td>${escapeHtml(row.executionRows)}</td><td>${escapeHtml(row.passed)}</td><td>${escapeHtml(row.failed)}</td><td>${escapeHtml(row.skipped)}</td><td>${escapeHtml(row.screenshots)}</td><td><a href="${pathToFileURL(row.filePath).href}">Open Excel</a></td></tr>`).join('')}</tbody></table>`;
}

function reportCard(label, value, ready) {
  return `<div class="card"><span class="muted">${escapeHtml(label)}</span><strong class="${ready ? 'ok' : 'missing'}">${escapeHtml(value)}</strong></div>`;
}

function fileLink(filePath, label) {
  return exists(filePath)
    ? `<a href="${pathToFileURL(filePath).href}">${escapeHtml(label)}</a>`
    : `<span class="missing">${escapeHtml(label)} unavailable</span>`;
}

function directoryLink(directory, label) {
  return exists(directory)
    ? `<a href="${pathToFileURL(directory).href}">${escapeHtml(label)}</a>`
    : `<span class="missing">${escapeHtml(label)} unavailable</span>`;
}

function fileCount(directory) {
  if (!exists(directory)) return 0;
  let count = 0;
  for (const entry of fs.readdirSync(directory, { withFileTypes: true })) {
    const child = path.join(directory, entry.name);
    count += entry.isDirectory() ? fileCount(child) : 1;
  }
  return count;
}

function exists(target) {
  return fs.existsSync(target);
}

function escapeHtml(value) {
  return String(value)
    .replaceAll('&', '&amp;')
    .replaceAll('<', '&lt;')
    .replaceAll('>', '&gt;')
    .replaceAll('"', '&quot;')
    .replaceAll("'", '&#39;');
}
