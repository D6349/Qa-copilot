import type { FlowCaseDefinition } from './agent-flow-cases';

type GuardrailCaseInput = Pick<
  FlowCaseDefinition,
  'id' | 'title' | 'description' | 'steps' | 'expectedResult' | 'tags'
> & Partial<Omit<
  FlowCaseDefinition,
  'id' | 'title' | 'description' | 'steps' | 'expectedResult' | 'tags'
>>;

function defineGuardrailCase(
  input: GuardrailCaseInput,
): FlowCaseDefinition {
  return {
    module: 'Guardrails',
    category: 'Functional',
    scenarioType: 'Positive',
    type: 'Automation',
    priority: 'P1',
    severity: 'High',
    preconditions: ['A valid authenticated June session is available.'],
    automatable: true,
    writeOperation: false,
    ...input,
  };
}

