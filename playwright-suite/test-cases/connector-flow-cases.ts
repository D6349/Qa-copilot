import type { FlowCaseDefinition } from './agent-flow-cases';

type ConnectorCaseInput = Pick<
  FlowCaseDefinition,
  'id' | 'title' | 'description' | 'steps' | 'expectedResult' | 'tags'
> & Partial<Omit<
  FlowCaseDefinition,
  'id' | 'title' | 'description' | 'steps' | 'expectedResult' | 'tags'
>>;

function defineConnectorCase(input: ConnectorCaseInput): FlowCaseDefinition {
  return {
    module: 'Connectors',
    category: 'Functional',
    scenarioType: 'Positive',
    type: 'Automation',
    priority: 'P1',
    severity: 'High',
    preconditions: ['A valid authenticated June session is available.'],
    automatable: true,
    writeOperation: false,
    ...input,
  };
}

