import type { FlowCaseDefinition } from './agent-flow-cases';

type AccountCaseInput = Pick<
  FlowCaseDefinition,
  'id' | 'title' | 'description' | 'steps' | 'expectedResult' | 'tags'
> & Partial<Omit<
  FlowCaseDefinition,
  'id' | 'title' | 'description' | 'steps' | 'expectedResult' | 'tags'
>>;

function defineAccountCase(input: AccountCaseInput): FlowCaseDefinition {
  return {
    module: 'Account preflight',
    category: 'Authentication',
    scenarioType: 'Positive',
    type: 'Automation',
    priority: 'P1',
    severity: 'Critical',
    preconditions: ['A valid authenticated June storage state is available.'],
    automatable: true,
    writeOperation: false,
    ...input,
  };
}

