function ux(id, feature, title, input) {
  return {
    id,
    feature,
    title,
    objective: input.objective,
    preconditions: input.preconditions || [
      'The tester is authenticated in an approved DEV or UAT business.',
      'Only synthetic Knowledge Base data and documents are used.',
    ],
    steps: input.steps,
    testData: input.testData || 'Synthetic Knowledge Base fixture; Chrome; viewport 1440 x 900.',
    expectedResult: input.expectedResult,
    category: input.category || 'UX',
    reviewMethod: input.reviewMethod || 'Manual visual, keyboard and interaction review with screenshot evidence.',
    priority: input.priority || 'P1',
    severity: input.severity || 'Major',
    environment: input.environment || 'DEV and UAT',
  };
}

