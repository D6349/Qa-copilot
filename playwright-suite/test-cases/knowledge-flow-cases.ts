import type { FlowCaseDefinition } from './agent-flow-cases';

type KnowledgeCaseInput = Pick<
  FlowCaseDefinition,
  'id' | 'title' | 'description' | 'steps' | 'expectedResult' | 'tags'
> & Partial<Omit<
  FlowCaseDefinition,
  'id' | 'title' | 'description' | 'steps' | 'expectedResult' | 'tags'
>>;

function defineKnowledgeCase(
  input: KnowledgeCaseInput,
): FlowCaseDefinition {
  return {
    module: 'Knowledge Base',
    category: 'Functional',
    scenarioType: 'Positive',
    type: 'Automation',
    priority: 'P1',
    severity: 'High',
    preconditions: ['A valid authenticated June session is available.'],
    automatable: true,
    writeOperation: false,
    ...input,
  };
}

