type UiComponentCaseInput = Pick<
  FlowCaseDefinition,
  'id' | 'title' | 'description' | 'steps' | 'expectedResult' | 'tags'
> & Partial<Omit<
  FlowCaseDefinition,
  'id' | 'title' | 'description' | 'steps' | 'expectedResult' | 'tags'
>>;

function defineUiComponentCase(
  input: UiComponentCaseInput,
): FlowCaseDefinition {
  return {
    module: 'UI Components',
    category: 'Functional',
    scenarioType: 'Positive',
    type: 'Automation',
    priority: 'P1',
    severity: 'High',
    preconditions: ['A valid authenticated June session is available.'],
    automatable: true,
    writeOperation: false,
    ...input,
  };
}

