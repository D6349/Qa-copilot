function pageObject(page, model) {
  const cls = `${pascal(page.name)}Page`;
  const fields = (model?.fields || []).filter((f) => !['submit', 'button'].includes(f.type));
  const buttons = (model?.buttons || []).filter((b) => b.text).slice(0, 15);

  const locatorLines = fields.map((f) => {
    const prop = camel(f.key);
    let loc;
    if (f.testId) loc = `this.page.getByTestId('${esc(f.testId)}')`;
    else if (f.label) loc = `this.page.getByLabel('${esc(f.label)}')`;
    else if (f.placeholder) loc = `this.page.getByPlaceholder('${esc(f.placeholder)}')`;
    else if (f.name) loc = `this.page.locator('[name="${esc(f.name)}"]')`;
    else if (f.id) loc = `this.page.locator('#${esc(f.id)}')`;
    else loc = `this.page.locator('${f.tag}').nth(0)`;
    return `  readonly ${prop}: Locator;`;
  }).join('\n');

  const locatorInit = fields.map((f) => {
    const prop = camel(f.key);
    let loc;
    if (f.testId) loc = `page.getByTestId('${esc(f.testId)}')`;
    else if (f.label) loc = `page.getByLabel('${esc(f.label)}')`;
    else if (f.placeholder) loc = `page.getByPlaceholder('${esc(f.placeholder)}')`;
    else if (f.name) loc = `page.locator('[name="${esc(f.name)}"]')`;
    else if (f.id) loc = `page.locator('#${esc(f.id)}')`;
    else loc = `page.locator('${f.tag}').nth(0)`;
    return `    this.${prop} = ${loc};`;
  }).join('\n');

  const buttonLines = buttons.map((b) => `  readonly ${camel(b.text)}Button: Locator;`).join('\n');
  const buttonInit = buttons.map((b) => (b.testId
    ? `    this.${camel(b.text)}Button = page.getByTestId('${esc(b.testId)}');`
    : `    this.${camel(b.text)}Button = page.getByRole('button', { name: '${esc(b.text)}' });`)).join('\n');

  const fillSig = fields
    .filter((f) => ['text', 'textarea', 'email', 'tel', 'url', 'password', 'number', 'search', 'date'].includes(f.type))
    .map((f) => `    ${camel(f.key)}?: string;`).join('\n');

  const fillBody = fields
    .filter((f) => ['text', 'textarea', 'email', 'tel', 'url', 'password', 'number', 'search', 'date'].includes(f.type))
    .map((f) => `    if (data.${camel(f.key)} !== undefined) await this.${camel(f.key)}.fill(data.${camel(f.key)});`)
    .join('\n');

  return `import { type Page, type Locator, expect } from '@playwright/test';

/**
 * ${cls}
 * Source: ${page.url}
 * Generated by QA Copilot from a live page scan. Locators follow the
 * getByRole / getByLabel / getByTestId order. No XPath.
 */
export class ${cls} {
  readonly page: Page;
  readonly path = '${new URL(page.url, 'http://x').pathname || '/'}';
${locatorLines}
${buttonLines}

  constructor(page: Page) {
    this.page = page;
${locatorInit}
${buttonInit}
  }

  async goto(): Promise<void> {
    await this.page.goto(this.path, { waitUntil: 'domcontentloaded' });
  }

  async fillForm(data: {
${fillSig}
  }): Promise<void> {
${fillBody || '    // no fillable text inputs detected on this page'}
  }

  async expectLoaded(): Promise<void> {
    await expect(this.page).toHaveURL(new RegExp(this.path.replace(/\\//g, '\\\\/')));
  }

  async expectFieldError(field: Locator, message?: string | RegExp): Promise<void> {
    const describedBy = await field.getAttribute('aria-describedby');
    const error = describedBy
      ? this.page.locator(\`#\${describedBy}\`)
      : field.locator('xpath=following::*[contains(@class,"error")][1]');
    await expect(error).toBeVisible();
    if (message) await expect(error).toContainText(message);
  }
}
`;
}

function specFile(page, cases, model) {
  const cls = `${pascal(page.name)}Page`;
  const importPath = `../../pages/${kebab(page.name)}.page`;

  const byCategory = cases.reduce((a, c) => {
    (a[c.category] = a[c.category] || []).push(c); return a;
  }, {});

  const blocks = Object.entries(byCategory).map(([cat, list]) => {
    const tests = list.map((c) => {
      const tags = [
        c.isSmoke ? '@smoke' : '',
        c.isRegression ? '@regression' : '',
        c.category === 'Security' ? '@security' : '',
        c.category === 'Accessibility' ? '@a11y' : '',
        c.category === 'API' ? '@api' : '',
      ].filter(Boolean).join(' ');

      const steps = c.steps.map((s) => `      await test.step('${esc(s.action).replace(/'/g, "\\'")}${s.data ? ` [${esc(s.data).slice(0, 40)}]` : ''}', async () => {
        // TODO implement — see expected result in the annotation above
      });`).join('\n');

      const pre = (c.preconditions || []).map((p) => `   * - ${esc(p)}`).join('\n');
      const data = Object.entries(c.testData || {})
        .map(([k, v]) => `   *   ${esc(k)}: ${esc(String(v)).slice(0, 80)}`).join('\n');

      return `  /**
   * ${esc(c.id)} — ${esc(c.title)}
   * ${esc(c.description || '')}
   *
   * Preconditions:
${pre || '   * - none'}
   *
   * Test data:
${data || '   *   none'}
   *
   * Expected: ${esc(c.expectedResult)}
   */
  test('${esc(c.id)} ${esc(c.title).replace(/'/g, "\\'")} ${tags}', async ({ page }) => {
    test.info().annotations.push(
      { type: 'caseId', description: '${esc(c.id)}' },
      { type: 'priority', description: '${c.priority}' },
      { type: 'severity', description: '${c.severity}' },
      { type: 'expected', description: '${esc(c.expectedResult).replace(/'/g, "\\'").slice(0, 400)}' },
    );

    const ${camel(page.name)} = new ${cls}(page);
    await ${camel(page.name)}.goto();

${steps}
  });`;
    }).join('\n\n');

    return `describe_${kebab(cat)}:{
${tests}
}`;
  });

  // build describe blocks properly
  const describeBlocks = Object.entries(byCategory).map(([cat, list]) => {
    const inner = blocks.find((b) => b.startsWith(`describe_${kebab(cat)}:`));
    const body = inner.slice(inner.indexOf('{') + 1, inner.lastIndexOf('}'));
    return `test.describe('${esc(page.module)} › ${esc(cat)}', () => {${body}});`;
  }).join('\n\n');

  return `import { test, expect } from '@playwright/test';
import { ${cls} } from '${importPath}';
import { validPan, validGstin, validAadhaar, validIfsc, invalidFor } from '../../utils/testData';

/**
 * ${page.name} — ${page.url}
 * ${cases.length} case(s) generated by QA Copilot.
 *
 * Each test carries its full manual steps as test.step() calls and its expected
 * result as an annotation, so the HTML report reads like the manual case.
 * Fill in the assertions inside each step.
 */

${describeBlocks}
`;
}

