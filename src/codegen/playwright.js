/**
 * codegen/playwright.js - turn selected test cases into a runnable
 * Playwright + TypeScript project: config, page objects, specs, auth fixture,
 * data factory, MySQL result logger, GitHub Actions workflow, README.
 *
 * Pure string templating. Nothing here calls a model.
 */

const pascal = (s) => String(s || 'Page')
  .replace(/[^A-Za-z0-9 ]/g, ' ')
  .split(/\s+/).filter(Boolean)
  .map((w) => w[0].toUpperCase() + w.slice(1).toLowerCase())
  .join('') || 'Page';

const kebab = (s) => String(s || 'page')
  .replace(/[^A-Za-z0-9]+/g, '-').replace(/^-|-$/g, '').toLowerCase() || 'page';

const camel = (s) => {
  const p = pascal(s);
  return p[0].toLowerCase() + p.slice(1);
};

const esc = (s) => String(s ?? '').replace(/\\/g, '\\\\').replace(/`/g, '\\`').replace(/\$\{/g, '\\${');

