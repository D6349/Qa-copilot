/**
 * testPlan.js - assemble an IEEE-829 style plan from real project data.
 * Template-driven: every number below is computed from the actual case list.
 */

const HOURS = { P1: 0.75, P2: 0.5, P3: 0.35, P4: 0.25 };

export function buildPlan({ project, cases, models = {} }) {
  const total = cases.length;
  const by = (k) => cases.reduce((a, c) => { a[c[k]] = (a[c[k]] || 0) + 1; return a; }, {});
  const byCat = by('category');
  const byPri = by('priority');
  const byMod = by('module');

  const manual = cases.filter((c) => c.type === 'Manual').length;
  const automation = total - manual;
  const smoke = cases.filter((c) => c.isSmoke).length;
  const automatable = cases.filter((c) => c.automatable).length;

  const manualHours = cases
    .filter((c) => c.type === 'Manual')
    .reduce((a, c) => a + (HOURS[c.priority] || 0.35), 0);
  const autoBuildHours = automation * 0.6;

  const envRows = Object.entries(project.environments || {})
    .filter(([, url]) => url)
    .map(([k, url]) => `| ${k.toUpperCase()} | ${url} |`).join('\n')
    || '| — | not configured |';

  const modRows = Object.entries(byMod)
    .sort((a, b) => b[1] - a[1])
    .map(([m, n]) => {
      const mc = cases.filter((c) => c.module === m);
      const h = mc.reduce((a, c) => a + (HOURS[c.priority] || 0.35), 0);
      return `| ${m} | ${n} | ${mc.filter((c) => c.type === 'Automation').length} | ${mc.filter((c) => c.priority === 'P1').length} | ${h.toFixed(1)} |`;
    }).join('\n') || '| — | 0 | 0 | 0 | 0 |';

  const pageRows = (project.pages || []).map((p) => {
    const n = cases.filter((c) => c.pageId === p.id).length;
    const m = models[p.id];
    return `| ${p.name} | ${p.module} | ${m ? m.fields.length : '—'} | ${n} | ${p.lastScannedAt ? p.lastScannedAt.slice(0, 10) : 'never'} |`;
  }).join('\n') || '| — | — | — | — | — |';

  const rtmRows = Object.entries(
    cases.reduce((acc, c) => {
      const key = c.requirementRef || `${c.module} / ${c.subModule || 'general'}`;
      (acc[key] = acc[key] || []).push(c.id);
      return acc;
    }, {}),
  ).map(([req, ids]) => `| ${req} | ${ids.length} | ${ids.slice(0, 6).join(', ')}${ids.length > 6 ? ` +${ids.length - 6} more` : ''} |`).join('\n');

  const catRows = Object.entries(byCat).sort((a, b) => b[1] - a[1])
    .map(([c, n]) => `| ${c} | ${n} | ${((n / total) * 100).toFixed(0)}% |`).join('\n');

  return `# Test Plan — ${project.name}

**Product:** ${project.product || '—'}
**Prepared:** ${new Date().toISOString().slice(0, 10)}
**Version:** 1.0
**Status:** Draft

---

## 1. Objective

Verify that ${project.name}${project.product ? ` (${project.product})` : ''} behaves correctly, safely and accessibly across all supported environments, browsers and user roles, and that no regression is introduced by the current release.

${project.description || '_Add the release-specific objective here._'}

## 2. Scope

### In scope
${(project.pages || []).map((p) => `- ${p.name} (\`${p.url}\`)`).join('\n') || '- _No pages added yet_'}
- Functional, validation, security, accessibility, API, performance and compatibility testing of the above
- ${automatable} of ${total} cases are automatable and will be added to the Playwright suite

### Out of scope
- Third-party payment gateway internals (covered by the provider's own certification)
- Load testing beyond the stated concurrency budget
- Native mobile apps
- Infrastructure and network-layer penetration testing

## 3. Test environment

| Environment | Base URL |
|---|---|
${envRows}

Browsers: Chrome (latest), Firefox (latest), Edge (latest), Safari (latest on macOS/iOS)
Viewports: 320, 768, 1280, 1920 px
Test data: generated by the built-in Indian-format factory (PAN, GSTIN, CIN, DIN, Aadhaar, IFSC, pincode) with valid checksums plus documented invalid variants.

## 4. Pages under test

| Page | Module | Fields | Cases | Last scanned |
|---|---|---|---|---|
${pageRows}

## 5. Test approach

| Approach | Cases | Share |
|---|---|---|
| Manual | ${manual} | ${total ? ((manual / total) * 100).toFixed(0) : 0}% |
| Automation | ${automation} | ${total ? ((automation / total) * 100).toFixed(0) : 0}% |
| Smoke subset | ${smoke} | ${total ? ((smoke / total) * 100).toFixed(0) : 0}% |

Automation is written in Playwright + TypeScript using the Page Object Model, executed per environment via \`BASE_URL\`, and results are written to the MySQL \`test_cases\` table. Manual cases cover judgement-based checks — error-message clarity, colour contrast, print layout and third-party OTP delivery.

## 6. Coverage by test type

| Category | Cases | Share |
|---|---|---|
${catRows || '| — | 0 | 0% |'}

Priority split: ${Object.entries(byPri).map(([p, n]) => `${p}=${n}`).join(', ') || '—'}

## 7. Module breakdown and estimate

| Module | Cases | Automated | P1 | Manual exec hrs |
|---|---|---|---|---|
${modRows}

**Estimate**
- Manual execution: ${manualHours.toFixed(1)} hours per full cycle
- Automation build: ${autoBuildHours.toFixed(1)} hours one-off
- Automated execution: under 1 hour per cycle once built
- Regression cycles planned: 3 (dev, UAT, pre-prod)

## 8. Entry criteria

- Build deployed to the target environment and smoke-passing
- All in-scope features code-complete and merged
- Test data and role-based test accounts provisioned for every role under test
- Requirements/acceptance criteria signed off and attached to this plan
- No P1 defects open from the previous cycle

## 9. Exit criteria

- 100% of P1 and P2 cases executed
- Zero open Critical or High defects
- Medium defects triaged with an owner and target release
- Automation suite green on the target environment
- Test summary report published and signed off

## 10. Roles and responsibilities

| Role | Responsibility |
|---|---|
| QA Engineer | Case design, execution, automation, defect logging |
| Dev Lead | Defect triage, fix turnaround, environment support |
| Product Owner | Requirement clarification, UAT sign-off, severity arbitration |
| DevOps | Environment availability, deployment, CI pipeline |

## 11. Defect management

**Severity**
| Level | Definition |
|---|---|
| Critical | Data loss, security breach, or the core flow cannot complete. No workaround. |
| High | Major function broken; a workaround exists but is not acceptable long-term. |
| Medium | Function partly impaired; acceptable workaround exists. |
| Low | Cosmetic, copy or minor UX issue. |

**Workflow:** New → Assigned → In Progress → Fixed → Retest → Closed / Reopened

Every defect carries: environment, build number, steps to reproduce, expected vs actual, evidence (screenshot, video or trace), the test case ID, and severity + priority.

## 12. Risks

| Risk | Impact | Mitigation |
|---|---|---|
| Environment instability during the cycle | Blocks execution | Agree a daily deployment window; keep a second environment warm |
| Requirements changing mid-cycle | Rework of cases | Re-scan affected pages and use the page-model diff to find impacted cases |
| Test data exhaustion (used PANs/GSTINs) | Blocks repeat runs | Data factory generates fresh valid values per run |
| Third-party dependency downtime | Blocks payment/OTP flows | Agree stub or sandbox credentials before the cycle starts |
| Automation flakiness | False failures erode trust | Role/label based locators only, no XPath, no fixed sleeps |

## 13. Requirement traceability matrix

| Requirement / area | Cases | Test case IDs |
|---|---|---|
${rtmRows || '| — | 0 | — |'}

## 14. Deliverables

- This test plan
- Test case repository (Excel export, one sheet per module)
- Playwright automation suite with HTML and Allure reports
- Defect log
- Test summary report
- Page-model snapshots for regression diffing

## 15. Tools

| Purpose | Tool |
|---|---|
| Case design and management | QA Copilot |
| Automation | Playwright + TypeScript |
| Reporting | Playwright HTML report, Allure |
| Results storage | MySQL \`test_cases\` |
| CI | GitHub Actions |
| Defect tracking | Jira |

---

_Generated by QA Copilot from ${total} test cases across ${(project.pages || []).length} page(s). Edit freely — this file is yours._
`;
}

export function buildSummaryReport({ project, cases }) {
  const n = cases.length;
  const c = (s) => cases.filter((x) => x.status === s).length;
  const pass = c('Pass'); const fail = c('Fail'); const blocked = c('Blocked');
  const skipped = c('Skipped'); const notRun = c('Not Run');
  const executed = n - notRun;

  return `# Test Summary Report — ${project.name}

**Date:** ${new Date().toISOString().slice(0, 10)}
**Environment:** _fill in_
**Build:** _fill in_

## Execution summary

| Metric | Count | % of total |
|---|---|---|
| Total cases | ${n} | 100% |
| Executed | ${executed} | ${n ? ((executed / n) * 100).toFixed(0) : 0}% |
| Passed | ${pass} | ${n ? ((pass / n) * 100).toFixed(0) : 0}% |
| Failed | ${fail} | ${n ? ((fail / n) * 100).toFixed(0) : 0}% |
| Blocked | ${blocked} | ${n ? ((blocked / n) * 100).toFixed(0) : 0}% |
| Skipped | ${skipped} | ${n ? ((skipped / n) * 100).toFixed(0) : 0}% |
| Not run | ${notRun} | ${n ? ((notRun / n) * 100).toFixed(0) : 0}% |

Pass rate of executed: **${executed ? ((pass / executed) * 100).toFixed(1) : 0}%**

## Failed cases

${cases.filter((x) => x.status === 'Fail').map((x) => `- **${x.id}** ${x.title}${x.actualResult ? ` — ${x.actualResult}` : ''}`).join('\n') || '_None_'}

## Blocked cases

${cases.filter((x) => x.status === 'Blocked').map((x) => `- **${x.id}** ${x.title}${x.actualResult ? ` — ${x.actualResult}` : ''}`).join('\n') || '_None_'}

## Recommendation

_Go / No-go, with reasoning._

## Observations and follow-ups

_Anything worth carrying into the next cycle._
`;
}
